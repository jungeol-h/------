-- 학생 퇴원일·신청취소일 마이그레이션 (학생 목록 보고서 표시용)
-- 배경: 학생 목록 보고서(PDF)에 입학일뿐 아니라 퇴원·신청취소 처리 일자도
--       보여달라는 요청 — 언제 상태가 바뀌었는지 서류상 확인 필요.
-- 방식: 퇴원·신청취소 처리(setStudentStatus) 시 그날 날짜를 상태별 컬럼에 기록.
--       재원 복구 시 값은 지우지 않고(표시는 현재 상태와 일치할 때만),
--       다시 퇴원·취소되면 그날 날짜로 덮어쓴다.
-- 과거분: 이 컬럼 도입 이전에 퇴원·신청취소 처리된 학생은 시점을 복원할
--       방법이 없어 NULL로 남는다 — 필요하면 관리자가 수기로 채워 넣는다.
-- 구 프런트 호환: 추가 전용(컬럼 추가만) — 구 프런트는 영향 없음.
-- ⚠️ 신 프런트는 이 컬럼에 쓰므로 반드시 코드 배포 전에 먼저 적용할 것
--       (미적용 시 퇴원·신청취소 처리가 컬럼 없음 오류로 실패).
-- 사용: Supabase Studio → SQL Editor → RUN (코드 배포 전에 먼저 실행)
-- 재실행 안전: IF NOT EXISTS
-- ============================================================

alter table users add column if not exists withdrawn_at date;
alter table users add column if not exists cancelled_at date;
